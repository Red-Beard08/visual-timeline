import assert from 'node:assert/strict';
import {build} from 'esbuild';
const out=await build({entryPoints:['src/composition.ts'],bundle:true,write:false,format:'esm'});
const {defaults,normalizeComposition,newLayer,newRow,reorder,matches,styleFor,placeRow}=await import('data:text/javascript;base64,'+Buffer.from(out.outputFiles[0].text).toString('base64'));
const config=defaults();assert.equal(config.views.length,3);assert.equal(config.views[1].rows.length,3);
assert.deepEqual(normalizeComposition(JSON.parse(JSON.stringify(config))),config);
const dirty=structuredClone(config);dirty.views[0].rows[0].height=-1;dirty.views[0].rows[0].layers[0].opacity=Infinity;
assert.equal(normalizeComposition(dirty).views[0].rows[0].height,120);
assert.equal(normalizeComposition(dirty).views[0].rows[0].layers[0].opacity,1);
assert.ok(normalizeComposition({views:[]}).views.length);
const record=(id,start,end)=>({id,title:id,type:'visual-timeline-person',categories:['king'],tags:['#israel'],date:{start,end}});
const r=record('King A','930 BC','900 BC'),l=newLayer();l.categories=['king'];l.tags=['israel'];
assert.ok(matches(r,l));l.types=['visual-timeline-event'];assert.ok(!matches(r,l));l.types=[];
assert.equal(styleFor(r,l,{king:'line',person:'dot'}),'line');l.style='box';assert.equal(styleFor(r,l,{king:'line'}),'box');
const row=newRow('Rulers',[l]),records=[r,record('King B','925 BC','890 BC'),record('King C','880 BC','860 BC')];
const layout=placeRow(row,records,{min:-1000,max:-800},1200,{});
assert.notEqual(layout.items[0].lane,layout.items[1].lane);
assert.equal(layout.items[2].lane,layout.items[0].lane);
const bg={...l,id:'background',plane:'background'};row.layers.push(bg);
const combined=placeRow(row,records,{min:-1000,max:-800},1200,{});
assert.equal(combined.items[0].layer.plane,'background');
assert.equal(combined.items[0].x,combined.items[3].x,'Shared dates align across planes');
assert.equal(combined.items[0].lane,combined.items[3].lane,'Background and foreground can overlay');
const order=['a','b','c'];reorder(order,2,0);assert.deepEqual(order,['c','a','b']);
reorder(order,0,99);assert.deepEqual(order,['a','b','c']);
l.enabled=false;assert.ok(!matches(r,l));
console.log('Validated composition persistence, defaults, filters, style overrides, row ordering, alignment, and collision lanes.');
